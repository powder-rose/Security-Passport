function normalizePathname(pathname) {
  const value =
    String(pathname || '/')
      .split('?')[0]
      .split('#')[0]
      .trim();

  if (
    !value ||
    value === '/'
  ) {
    return '/';
  }

  return (
    '/' +
    value
      .replace(/^\/+|\/+$/g, '') +
    '/'
  );
}


export function getObjectTypeByPathname(
  pathname,
) {
  const normalized =
    normalizePathname(pathname);

  return (
    objectTypes.find(
      (item) =>
        item.path === normalized,
    ) || null
  );
}


export function isObjectTypePathname(
  pathname,
) {
  return Boolean(
    getObjectTypeByPathname(
      pathname,
    ),
  );
}
